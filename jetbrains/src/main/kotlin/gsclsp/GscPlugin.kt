package gsclsp

import com.google.gson.JsonObject
import com.google.gson.JsonParser
import com.intellij.ide.plugins.PluginManagerCore
import com.intellij.openapi.extensions.PluginId
import com.intellij.openapi.util.SystemInfo
import com.intellij.util.system.CpuArch
import java.nio.file.Files
import java.nio.file.Path
import java.util.Properties
import kotlin.io.path.isDirectory
import kotlin.io.path.listDirectoryEntries
import kotlin.io.path.reader

const val SERVER_ID = "gscLanguageServer"
const val SETTINGS_SECTION = "GSC"

data class Featureset(val id: String, val displayName: String, val description: String)

data class Engine(val id: String, val displayName: String, val gameTitle: String, val featuresets: List<Featureset>)

/** Files shipped with the plugin (see `prepareSandbox` in build.gradle.kts) and build information. */
object GscPlugin {
	private val pluginPath: Path by lazy {
		PluginManagerCore.getPlugin(PluginId.getId("gsclsp"))!!.pluginPath
	}

	val serverDir: Path get() = pluginPath.resolve("server")
	val serverScript: Path get() = serverDir.resolve("server.js")
	val textMateBundle: Path get() = pluginPath.resolve("textmate")

	private val properties: Properties by lazy {
		Properties().apply {
			GscPlugin::class.java.getResourceAsStream("/gsclsp.properties")!!.use(::load)
		}
	}
	val version: String get() = properties.getProperty("version")
	val githubRepository: String get() = properties.getProperty("githubRepository").orEmpty()

	/** Release asset of the standalone server for this OS, see .github/workflows/release.yml. */
	val releaseAsset: String
		get() {
			val platform = when {
				SystemInfo.isWindows -> "windows-x64"
				SystemInfo.isMac -> if (CpuArch.isArm64()) "macos-arm64" else "macos-x64"
				else -> "linux-x64"
			}
			return "gsclsp-$platform.zip"
		}

	val engines: List<Engine> by lazy {
		val dataDir = serverDir.resolve("data")
		dataDir.listDirectoryEntries().filter { it.isDirectory() }.sorted().map { dir ->
			val json = dir.resolve("engine.json").reader().use { JsonParser.parseReader(it).asJsonObject }
			Engine(
				id = json["id"].asString,
				displayName = json["displayName"].asString,
				gameTitle = json["gameTitle"].asString,
				featuresets = json["featuresets"].asJsonArray.map { it.asJsonObject }.map {
					Featureset(it["id"].asString, it["displayName"].asString, it["description"].asString)
				},
			)
		}
	}

	/** The server's default settings section, generated by the server build. */
	val defaultSettings: JsonObject by lazy {
		Files.newBufferedReader(serverDir.resolve("default-settings.json")).use {
			JsonParser.parseReader(it).asJsonObject[SETTINGS_SECTION].asJsonObject
		}
	}

	/** JSON Schema of the settings section, generated by the server build. */
	private val settingsSchema: JsonObject by lazy {
		Files.newBufferedReader(serverDir.resolve("settings.schema.json")).use {
			JsonParser.parseReader(it).asJsonObject["properties"].asJsonObject[SETTINGS_SECTION].asJsonObject
		}
	}

	/** Allowed values of an enum setting (`path` are property names below the settings section). */
	fun settingOptions(vararg path: String): List<String> {
		val property = path.fold(settingsSchema) { schema, key -> schema["properties"].asJsonObject[key].asJsonObject }
		return property["enum"].asJsonArray.map { it.asString }
	}
}
